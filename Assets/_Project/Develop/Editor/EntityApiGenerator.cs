using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using _Project.Develop.Runtime.Gameplay.EntitiesCore;
using _Project.Develop.Runtime.Gameplay.EntitiesCore.Systems;
using UnityEditor;
using UnityEngine;

namespace _Project.Develop.Editor
{
	public static class EntityApiGenerator
	{
		private const string OutputPath = "Assets/_Project/Develop/Runtime/Gameplay/EntitiesCore/Generated/EntityApi.cs";

		[MenuItem("Project/Generate Entity Api")]
		public static void Generate()
		{
			Type[] allTypes = AppDomain.CurrentDomain.GetAssemblies()
				.SelectMany(assembly => assembly.GetTypes())
				.Where(type => type.IsClass && type.IsAbstract == false)
				.ToArray();

			Type[] componentTypes = allTypes
				.Where(type => typeof(IEntityComponent).IsAssignableFrom(type))
				.OrderBy(type => type.Name)
				.ToArray();

			Type[] systemTypes = allTypes
				.Where(type => typeof(IEntitySystem).IsAssignableFrom(type))
				.OrderBy(type => type.Name)
				.ToArray();

			StringBuilder builder = new StringBuilder();

			builder.AppendLine("// <auto-generated/>");
			builder.AppendLine("namespace _Project.Develop.Runtime.Gameplay.EntitiesCore");
			builder.AppendLine("{");
			builder.AppendLine("\tpublic partial class Entity");
			builder.AppendLine("\t{");

			for (int i = 0; i < componentTypes.Length; i++)
			{
				AppendComponentApi(builder, componentTypes[i]);

				if (i < componentTypes.Length - 1 || systemTypes.Length > 0)
					builder.AppendLine();
			}

			for (int i = 0; i < systemTypes.Length; i++)
			{
				AppendSystemApi(builder, systemTypes[i]);

				if (i < systemTypes.Length - 1)
					builder.AppendLine();
			}

			builder.AppendLine("\t}");
			builder.AppendLine("}");

			string fullPath = Path.Combine(Directory.GetCurrentDirectory(), OutputPath);
			Directory.CreateDirectory(Path.GetDirectoryName(fullPath));
			File.WriteAllText(fullPath, builder.ToString());

			AssetDatabase.ImportAsset(OutputPath);
			Debug.Log($"EntityApi generated: {componentTypes.Length} components, {systemTypes.Length} systems -> {OutputPath}");
		}

		private static void AppendComponentApi(StringBuilder builder, Type componentType)
		{
			string componentTypeName = GetFriendlyTypeName(componentType);
			string componentName = componentType.Name;

			FieldInfo valueField = componentType.GetField("Value", BindingFlags.Public | BindingFlags.Instance);

			if (valueField == null)
			{
				Debug.LogWarning($"EntityApiGenerator: component {componentTypeName} has no public 'Value' field, skipped");
				return;
			}

			Type valueType = valueField.FieldType;
			string valueTypeName = GetFriendlyTypeName(valueType);

			bool canAutoConstructValue = valueType.IsClass
				&& typeof(UnityEngine.Object).IsAssignableFrom(valueType) == false
				&& valueType.GetConstructor(Type.EmptyTypes) != null;

			builder.AppendLine($"\t\tpublic {componentTypeName} {componentName}C => GetComponent<{componentTypeName}>();");
			builder.AppendLine($"\t\tpublic {valueTypeName} {componentName} => {componentName}C.Value;");
			builder.AppendLine($"\t\tpublic Entity Add{componentName}({valueTypeName} value = default)");
			builder.AppendLine("\t\t{");
			builder.AppendLine($"\t\t\tvar component = new {componentTypeName}();");

			if (canAutoConstructValue)
				builder.AppendLine($"\t\t\tcomponent.Value = value ?? new {valueTypeName}();");
			else
				builder.AppendLine("\t\t\tcomponent.Value = value;");

			builder.AppendLine("\t\t\tAddComponent(component);");
			builder.AppendLine("\t\t\treturn this;");
			builder.AppendLine("\t\t}");
		}

		private static void AppendSystemApi(StringBuilder builder, Type systemType)
		{
			string systemTypeName = GetFriendlyTypeName(systemType);
			string systemName = systemType.Name;

			ConstructorInfo constructor = systemType.GetConstructors()
				.OrderByDescending(c => c.GetParameters().Length)
				.FirstOrDefault();

			ParameterInfo[] parameters = constructor != null
				? constructor.GetParameters()
				: Array.Empty<ParameterInfo>();

			string parameterList = string.Join(", ", parameters
				.Select(p => $"{GetFriendlyTypeName(p.ParameterType)} {p.Name}"));

			string argumentList = string.Join(", ", parameters.Select(p => p.Name));

			builder.AppendLine($"\t\tpublic Entity Add{systemName}({parameterList})");
			builder.AppendLine("\t\t{");
			builder.AppendLine($"\t\t\tAddSystem(new {systemTypeName}({argumentList}));");
			builder.AppendLine("\t\t\treturn this;");
			builder.AppendLine("\t\t}");
		}

		private static string GetFriendlyTypeName(Type type)
		{
			if (type.IsGenericType == false)
				return type.FullName.Replace('+', '.');

			string genericArguments = string.Join(", ", type.GetGenericArguments().Select(GetFriendlyTypeName));
			string baseName = type.GetGenericTypeDefinition().FullName;
			baseName = baseName.Substring(0, baseName.IndexOf('`'));

			return $"{baseName.Replace('+', '.')}<{genericArguments}>";
		}
	}
}
